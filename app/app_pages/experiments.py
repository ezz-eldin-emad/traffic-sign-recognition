import pandas as pd
import streamlit as st
from PIL import Image

from src.config import MODEL_REGISTRY
from app.app_pages.common import (
    DISPLAY_IMAGE_SIZE,
    available_models,
    fit_image_to_box,
    run_prediction,
)


st.title("Experiments")
st.caption("Upload one image and compare the saved deep-learning models.")

with st.form("experiment_form"):
    uploaded_file = st.file_uploader(
        "Upload a traffic-sign image",
        type=["jpg", "jpeg", "png"],
    )
    submitted = st.form_submit_button("Run models", type="primary")

if uploaded_file is None:
    st.info("Upload an image to begin an experiment.")
    st.stop()

try:
    image = Image.open(uploaded_file).convert("RGB")
except Exception as exc:
    st.error(f"Could not read this image: {exc}")
    st.stop()

with st.container(horizontal_alignment="center"):
    st.image(
        fit_image_to_box(image),
        caption=f"Uploaded image ({image.width} × {image.height}px)",
        width=DISPLAY_IMAGE_SIZE,
    )
if not submitted:
    st.info("Press Run models to generate predictions and Grad-CAM views.")
    st.stop()

models = available_models()
if not models:
    st.error("No saved deep-learning model was found in models/.")
    st.stop()

st.subheader("Model results")
st.caption(
    "The display size is fixed for readability. The original image is kept in "
    "the same aspect ratio."
)

for model_name in models:
    display_name = MODEL_REGISTRY[model_name]["display_name"]
    with st.container(border=True):
        st.subheader(display_name)
        try:
            with st.spinner(f"Running {display_name}..."):
                result = run_prediction(model_name, image)
        except Exception as exc:
            st.error(f"{display_name} failed: {exc}")
            continue

        metric_columns = st.columns(2)
        with metric_columns[0]:
            st.metric("Prediction", result["label"])
        with metric_columns[1]:
            st.metric("Confidence", f"{result['confidence']:.2%}")

        st.dataframe(
            pd.DataFrame(result["top3"]),
            hide_index=True,
            width="stretch",
        )

        if result["gradcam_available"]:
            view_columns = st.columns(2)
            with view_columns[0]:
                st.image(
                    fit_image_to_box(result["heatmap"]),
                    caption="Grad-CAM heatmap",
                    width=DISPLAY_IMAGE_SIZE,
                )
            with view_columns[1]:
                st.image(
                    fit_image_to_box(result["overlay"]),
                    caption="Grad-CAM overlay",
                    width=DISPLAY_IMAGE_SIZE,
                )
        else:
            st.info(
                "Grad-CAM is unavailable for this TensorFlow Lite deployment "
                "artifact. Its prediction is generated by the quantized model."
            )
